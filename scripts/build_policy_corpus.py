def main():
    existing_ids = set()
    if os.path.exists(DOCS):
        with open(DOCS, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    existing_ids.add(json.loads(line).get("id"))

    new_docs, new_chunks = [], []
    for p in POLICIES:
        if p["id"] in existing_ids:
            print(f"[skip] {p['id']} 已存在")
            continue
        new_docs.append({
            "id": p["id"],
            "category": "policy",
            "title": p["title"],
            "source": p["source"],
            "url": p["url"],
            "date": p["date"],
            "tags": p["tags"],
            # 政策类不存全文：body 仅作"条款摘编"声明，检索引用统一标注「条款摘编」（必修 2）
            "body": "（政策类语料为条款摘编，非法规全文镜像；引用均已标注「条款摘编」，请以官方原文为准）",
            "meta": p["meta"],
        })
        for clause, text in p["chunks"]:
            new_chunks.append({"doc_id": p["id"], "clause": clause, "text": text})

    with open(DOCS, "a", encoding="utf-8") as f:
        for d in new_docs:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")
    with open(CHUNKS, "a", encoding="utf-8") as f:
        for c in new_chunks:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")

    print(f"[policy] appended docs={len(new_docs)} chunks={len(new_chunks)}")


if __name__ == "__main__":
    main()
